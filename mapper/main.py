import logging
from .mapper import Mapper
from .parser import Parser
from .instruction import Instruction

import argparse


def generateInstructions(kernel, DFG):
    instructions = {}
    inst_id = 0
    for t in kernel:
        for p in kernel[t]:
            node_id = kernel[t][p]
            inst = Instruction(inst_id, node_id)
            inst.pe = p
            inst.time = t
            n = DFG.getNode(node_id)
            inst.ROp = n.rOp_id
            inst.LOp = n.lOp_id
            inst.name = n.name
            inst.predicate = n.predicate_id
            inst.opcode = n.opcode
            inst_id += 1
            if DFG.getConstant(n.id) != None:
                inst.immediate = DFG.getConstant(n.id).immediate
            if p not in instructions:
                instructions[p] = []
            instructions[p].append(inst)

    return instructions


CGRA_X = 4
CGRA_Y = 4
CGRA_R = 100


def main():

    global CGRA_X, CGRA_Y, CGRA_R

    parser = argparse.ArgumentParser(description='SAT-MapIt mapper usage')
    parser.add_argument('-path', type=str, help='Path of the folder containing the extracted DFG')
    parser.add_argument(
        '-x', type=int, help='Number or rows in the CGRA (default value: 4)', default=4
    )
    parser.add_argument(
        '-y', type=int, help='Number or rows in the CGRA (default value: 4)', default=4
    )
    parser.add_argument(
        '-r', type=int, help='Number of internal registers (default value: 5)', default=5
    )
    parser.add_argument(
        '-no_assembly',
        type=bool,
        help='Disable assmbly generation (only return the mapping)',
        default=False,
    )
    parser.add_argument(
        '--log',
        type=str,
        default="WARNING",
        help='The log level. Possible values are "DEBUG", "INFO", "WARNING", "ERROR" and "CRITICAL"',
    )
    parser.add_argument(
        '--log-file',
        type=str,
        default="out.log",
        help='The file inside which the logs will be stored',
    )
    parser.add_argument(
        '-s',
        '--save-smt2-and-cnf',
        action="store_true",
        help='If the flag is given, save the smt2 and cnf files for the smallest II found',
    )
    parser.add_argument(
        "-t",
        "--timeout",
        type=int,
        help="The amount of time after which z3 stops trying to solve. In milliseconds. If option not given, z3 will not timeout",
    )
    parser.add_argument(
        "-m",
        "--model",
        default=0,
        type=int,
        help="The model to be used. 0 is the default and the first one z3 will find, 1 is the second one, etc.",
    )
    # Parse Arguments
    args = parser.parse_args()

    loglevel = args.log
    logfile = args.log_file

    numeric_level = getattr(logging, loglevel.upper(), None)
    if not isinstance(numeric_level, int):
        raise ValueError('Invalid log level: %s' % loglevel)
    logging.basicConfig(
        format="%(levelname)s - %(message)s", filemode='w', filename=logfile, level=numeric_level
    )

    CGRA_X = int(args.x)
    CGRA_Y = int(args.y)
    CGRA_R = int(args.r)

    no_assembly = bool(args.no_assembly)

    # Path to the folder containing the benchmark
    path = args.path
    bench = "acc"
    # Names of the files generated by the LLVM pass
    nodefile = path + bench + "_nodes"
    edgefile = path + bench + "_edges"

    # Parse all the files generated by the LLVM pass
    p = Parser()
    p.parseNodeFile(nodefile)
    p.parseEdgeFile(edgefile)

    # Get the parsed DFG
    DFG = p.getDFG()

    # Initialize the mapper with the CGRA dimensions,
    # number of registers of each PE and the DFG
    m = Mapper(CGRA_X, CGRA_Y, CGRA_R, DFG, bench)

    # Find the mapping and get the mapped kernel
    m.findMapping(
        save_smt2_and_cnf=args.save_smt2_and_cnf,
        timeout_ms=args.timeout,
        model_number=args.model,
    )
    kernel = m.getKernel()

    # Generate instructions for the kernel, final mapping and than assembly
    # A node in the DFG does not contain all the information needed to
    # generate the assembly code, that's why we generate the list instructions
    # Final mapping is:
    # Initialization (e.g., live in loading) + Prologue + Kernel + Epilogue + Finalization (e.g., store of liveout)
    instructions = generateInstructions(kernel, DFG)
    m.generateMapping(instructions)
    assembly = m.getAssembly()
    with open("assembly", "w") as f:
        f.write(assembly)
    print(assembly)

    # Debug
    for p in instructions:
        for inst in instructions[p]:
            tmps = f"Id: {inst.nodeid} name: {inst.name} time: {inst.time} pe: {inst.pe}"
            tmps += f"Rout: {inst.getOutputOperandAssignedRegister()} opA: {inst.getLeftOperandAssignedRegister()} opB: {inst.getRigthOperandAssignedRegister()} immediate: {inst.immediate}"
            logging.debug(tmps + "\n")


if __name__ == "__main__":
    main()
